/* =============================================================================
 * sort.c —— 第二日 · 第 10 集：一段真程序（冒泡排序）
 *
 * 这颗核只认最小 RV64I，所以这段 C 有两处"故意"：
 *   1. 数组元素是 long（8 字节）——本日的访存只有双字（LD/SD），
 *      int（LW/SW）、char（LB/SB）都还不在这台机器的字典里。
 *   2. 全程没有乘除法——M 扩展是第五日的事；下标换算 a[j]*8 由编译器
 *      自己长成一条 slli。
 * 其余就是普通的冒泡排序：扫一趟，逆序就换；有一趟一个都没换就收尾。
 *
 * 收尾之后它再从头部比一遍——**排好序没有，由程序自己判**，判过了才把 done 置 1。
 * 最后那个 while 是停机：完工位已经立起，CPU 就留在这儿自转，等测试台收走这一拍。
 * ============================================================================= */

long a[6] = {9, 7, 5, 3, 2, 1};   /* 待排的六个数，初值编进镜像 */
volatile long done = 0;           /* 完工位：run 的 until 判的就是它 */

void sort(void)
{
    long pass, j, t;

    for (pass = 0; pass < 6; pass = pass + 1) {
        long swapped = 0;
        long limit = 6 - pass - 1;
        for (j = 0; j < limit; j = j + 1) {
            if (a[j] > a[j + 1]) {
                t = a[j]; a[j] = a[j + 1]; a[j + 1] = t;
                swapped = 1;
            }
        }
        if (swapped == 0)
            break;
    }

    long ok = 1;
    for (j = 1; j < 6; j = j + 1)
        if (a[j - 1] > a[j])
            ok = 0;

    if (ok)
        done = 1;

    while (done == 1)
        ;
}
